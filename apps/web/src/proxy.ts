import { NextResponse, type NextRequest } from 'next/server';

const sandboxOrigin = new URL(process.env.NEXT_PUBLIC_SANDBOX_URL ?? 'http://127.0.0.1:3100')
  .origin;

/**
 * Per-request CSP nonce. Next.js puts the nonce on its own scripts during dynamic rendering
 * (every page is dynamic: the root layout reads cookies). `'strict-dynamic'` lets those trusted
 * scripts load further code (Monaco's loader), while injected inline scripts are refused.
 * Styles keep `'unsafe-inline'`: Monaco and next/font inject style elements at runtime.
 */
export function buildCsp(nonce: string, dev: boolean): string {
  return [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${dev ? " 'unsafe-eval'" : ''}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self' data:",
    `connect-src 'self'${dev ? ' ws: wss:' : ''}`,
    `frame-src ${sandboxOrigin}`,
    "worker-src 'self' blob:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

export function proxy(request: NextRequest) {
  const nonce = Buffer.from(crypto.randomUUID()).toString('base64');
  const csp = buildCsp(nonce, process.env.NODE_ENV === 'development');
  const requestHeaders = new Headers(request.headers);
  requestHeaders.set('x-nonce', nonce);
  requestHeaders.set('Content-Security-Policy', csp);
  const response = NextResponse.next({ request: { headers: requestHeaders } });
  response.headers.set('Content-Security-Policy', csp);
  return response;
}

export const config = {
  matcher: [
    {
      // Pages only: not the API proxy, build assets, Monaco files or the icon.
      source: '/((?!api|_next/static|_next/image|monaco|favicon.ico|icon.svg).*)',
      missing: [
        { type: 'header', key: 'next-router-prefetch' },
        { type: 'header', key: 'purpose', value: 'prefetch' },
      ],
    },
  ],
};
